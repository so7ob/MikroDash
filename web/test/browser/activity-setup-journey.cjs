const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const { AxeBuilder } = require('@axe-core/playwright');
(async () => {
  const base = process.argv[2];
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
  await context.addCookies([{ name: 'mikrodash_sid', value: 'activity-test-token', url: base }]);
  const page = await context.newPage();
  const errors = [], writes = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => {
    if (r.method() !== 'GET') writes.push(r.method() + ' ' + new URL(r.url()).pathname);
    if (new URL(r.url()).pathname === '/api/activity/setup') checks.push(r.url());
  });
  const settled = () => page.waitForFunction(() => document.querySelector('#page-activity')?.getAttribute('aria-busy') === 'false' && document.querySelector('#activitySetupPanel')?.getAttribute('aria-busy') === 'false');
  const mode = async value => { const r = await context.request.post(base + '/fixture/setup', { data: { mode: value } }); assert.equal(r.status(), 200); };
  const activity = async () => { await page.goto(base + '/activity?routerId=r1&tab=sync'); await settled(); };
  await activity();
  assert.equal(await page.locator('#activitySetupPrompt').isVisible(), true);
  const href = await page.locator('#activitySetupLink').getAttribute('href');
  const target = new URL(href, base);
  assert.equal(target.pathname, '/config-management');
  assert.equal(target.searchParams.get('template'), 'canned:activity-logging');
  assert.equal(target.searchParams.get('routerId'), 'r1');
  assert.equal(target.searchParams.get('archivePath'), 'usb-test/Activity/netlog');
  const initial = checks.length;
  await page.locator('[data-view="summary"]').click(); await settled();
  await page.locator('#activitySearch').fill('synthetic');
  await page.waitForTimeout(450); await settled();
  await page.locator('[data-view="events"]').click(); await settled();
  assert.equal(checks.length, initial, 'filters/tabs re-read router setup');
  await page.locator('#activitySetupLink').focus(); await page.keyboard.press('Enter');
  await page.waitForURL('**/config-management?**');
  await page.waitForFunction(() => document.querySelector('#cfgDrawerBody')?.textContent?.includes('BEFORE DEPLOYING'));
  assert.match(await page.locator('#cfgDrawerTitle').textContent(), /Activity analytics/);
  await page.keyboard.press('Escape');
  await page.locator('[data-cfg-id="canned:activity-logging"] [data-cfg-act="deploy"]').click();
  assert.equal(await page.locator('[data-dep-val="r1"][data-dep-var="archive_path"]').inputValue(), 'usb-test/Activity/netlog');
  assert.equal(await page.locator('#cfgDepStart').isDisabled(), true);
  await mode(1); await activity();
  assert.match(await page.locator('#activitySetupStatus').textContent(), /Required logging settings found/);
  assert.equal(await page.locator('#activitySetupPrompt').isVisible(), false);
  await mode(2); await page.locator('#activityCheckSetup').click(); await settled();
  assert.match(await page.locator('#activitySetupStatus').textContent(), /could not be read/);
  assert.equal(await page.locator('#activitySetupPrompt').isVisible(), false, 'failed read recommends installation');
  await mode(3); await page.locator('#activityCheckSetup').click(); await settled();
  assert.equal(await page.locator('#activitySetupPrompt').isVisible(), true);
  assert.match(await page.locator('#activitySetupPromptText').textContent(), /Ask an administrator/);
  assert.equal(await page.locator('#activitySetupLink').isVisible(), false);
  // Hold an old result while selecting another router; no stale CTA may appear.
  await mode(0);
  await page.route('**/api/activity/setup?routerId=r1', async route => {
    const response = await route.fetch(); await new Promise(resolve => setTimeout(resolve, 350));
    await route.fulfill({ response }).catch(() => {});
  });
  const pending = page.waitForRequest('**/api/activity/setup?routerId=r1');
  await page.locator('#activityCheckSetup').click(); await pending;
  await page.locator('#activityRouter').selectOption('r2'); await settled();
  await page.waitForTimeout(450);
  assert.match(await page.locator('#activitySetupStatus').textContent(), /Required logging settings found/);
  assert.equal(await page.locator('#activitySetupPrompt').isVisible(), false);
  await page.unroute('**/api/activity/setup?routerId=r1');
  await activity();
  await page.locator('#activitySetupPanel details').evaluate(e => e.open = true);
  assert.equal(await page.locator('#activitySetupChecks li').count(), 6);
  for (const [width, theme, palette] of [[1280, 'dark', ''], [375, 'light', ''], [375, 'dark', 'nord']]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.evaluate(({ theme, palette }) => { document.documentElement.dataset.theme = theme; document.documentElement.dataset.palette = palette; }, { theme, palette });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'setup overflow');
    const axe = await new AxeBuilder({ page }).include('#page-activity').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    assert.deepEqual(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), [], 'setup accessibility');
    await page.screenshot({ path: '/tmp/mikrodash-activity-setup-' + width + '-' + theme + palette + '.png', fullPage: true, animations: 'disabled' });
  }
  assert.deepEqual(writes, [], 'setup/navigation applied changes');
  assert.deepEqual(errors, []);
  console.log('setup: missing/ready/unreadable/admin-only CTA, explicit recheck, no per-filter reads, stale router request, keyboard navigation to the real template with router/path prefill and guarded Deploy; 375/1280, light/dark/Nord and axe zero violations; zero page mutation requests');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
