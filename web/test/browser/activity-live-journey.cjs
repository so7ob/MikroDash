const assert=require('node:assert/strict');
module.exports=async function(page,settled){
 await page.locator('[data-view="summary"]').click();await settled();
 await require('./activity-preparing-journey.cjs')(page,settled);
 let requests=[];
 const listener=req=>{if(new URL(req.url()).pathname==='/api/activity/query')requests.push(new URL(req.url()).searchParams)};
 page.on('request',listener);
 const markup=await page.locator('#activityTimeline').innerHTML();
 await page.evaluate(()=>window.dispatchEvent(new Event('fixture-status')));
 await page.waitForTimeout(650);
 assert.equal(requests.length,0,'status notification reloaded analytics');
 await page.locator('[data-view="events"]').click();await settled();
 assert.equal(requests.at(-1).get('parts'),'table');
 assert.equal(await page.locator('#activityTimeline').innerHTML(),markup,'hidden timeline was redrawn');
 await page.locator('#activityNext').click();await settled();
 assert.ok(requests.at(-1).get('cursor'),'next page did not use cursor');
 const anchor=await page.locator('#activityTableBody tr').first().getAttribute('data-event-id');
 const focus=page.locator('#activityTableBody tr').first().locator('button').first();await focus.focus();
 const scroll=await page.locator('#activityTableBody').evaluate(e=>{const p=e.closest('.table-wrap')||e.parentElement.parentElement;p.scrollTop=50;return p.scrollTop});
 requests=[];
 await page.route('**/api/activity/query?**',async route=>{await new Promise(r=>setTimeout(r,750));await route.continue()});
 await page.evaluate(()=>{window.dispatchEvent(new Event('fixture-invalidate'));window.dispatchEvent(new Event('fixture-invalidate'));});
 await page.waitForTimeout(650);
 await page.evaluate(()=>{window.dispatchEvent(new Event('fixture-invalidate'));window.dispatchEvent(new Event('fixture-invalidate'));});
 await page.waitForTimeout(2200);await settled();
 await page.unroute('**/api/activity/query?**');
 assert.ok(requests.length>=1 && requests.length<=2,'invalidation burst was not coalesced');
 assert.ok(requests.every(q=>q.get('anchor')),'background page refresh lost its reference');
 assert.equal(await page.locator('#activityTableBody tr').first().getAttribute('data-event-id'),anchor);
 assert.equal(await focus.evaluate(e=>document.activeElement===e),true,'background refresh lost keyboard focus');
 assert.equal(await page.locator('#activityTableBody').evaluate(e=>(e.closest('.table-wrap')||e.parentElement.parentElement).scrollTop),scroll);
 // A new router intent cancels pending data and cannot display an old response.
 await page.route('**/api/activity/query?**',async route=>{if(new URL(route.request().url()).searchParams.get('routerId')==='r1')await new Promise(r=>setTimeout(r,900));try{await route.continue()}catch{/* canceled by the new intent */}});
 await page.evaluate(()=>window.dispatchEvent(new Event('fixture-invalidate')));await page.waitForTimeout(650);
 await page.locator('#activityRouter').selectOption('r2');await settled();
 assert.equal(await page.locator('#activityError').isVisible(),true,'denied router was not rejected');
 await page.waitForTimeout(1000);
 assert.equal(await page.locator('#activityTableBody tr[data-event-id]').count(),0,'late old-router response replaced denied view');
 await page.unroute('**/api/activity/query?**');
 await page.locator('#activityRouter').selectOption('r1');await settled();
 await page.locator('[data-view="sync"]').click();await settled();
 assert.equal(requests.at(-1).get('parts'),'status');
 await page.locator('[data-view="rules"]').click();await settled();
 assert.equal(requests.at(-1).get('parts'),'rules');
 await page.locator('[data-view="summary"]').click();await settled();
 page.off('request',listener);
 console.log('live activity: visible parts, status isolation, cursor navigation, coalescing, anchor/focus/scroll preservation passed');
};
