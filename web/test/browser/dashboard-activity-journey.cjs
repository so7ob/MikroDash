const { chromium } = require('playwright');
const { AxeBuilder } = require('@axe-core/playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
  const base = process.argv[2];
  await context.addCookies([{ name: 'mikrodash_sid', value: 'activity-test-token', url: base }]);
  const page = await context.newPage(); const errors = []; let requests = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().includes('/api/activity/dashboard?')) requests++; });
  const socket = async (event, data) => page.evaluate(d => window.dispatchEvent(new CustomEvent('fixture-socket', { detail: d })), { event, data });
  const count = async value => page.waitForFunction(n => document.querySelector('#dc-activity-overview strong')?.textContent === String(n), value);
  const edit = async () => page.locator('#dashEditBtn').click();
  const add = async title => {
    if (!(await page.locator('#dashAddPanel').evaluate(node => node.classList.contains('open')))) await page.locator('#dashAddCardBtn').click();
    await page.locator('#dashAddPanel button').filter({ hasText: title }).click();
  };
  await page.goto(base + '/home'); await page.waitForTimeout(200); assert.equal(requests, 0, 'hidden Activity cards fetched data');
  await edit();
  // Arrange a synthetic dashboard containing the six new optional cards.
  while (await page.locator('.dash-card:visible .dash-remove-btn').count()) await page.locator('.dash-card:visible .dash-remove-btn').first().click();
  await page.locator('#dashAddCardBtn').click();
  assert.equal(await page.locator('#dashAddPanel button').filter({ hasText: 'Activity ' }).count(), 6);
  await add('Activity Overview'); await count(12);
  const before = await page.locator('#dc-card-activity-overview').boundingBox();
  const handle = await page.locator('#dc-card-activity-overview .dash-resize.se').boundingBox();
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2); await page.mouse.down();
  await page.mouse.move(handle.x + 55, handle.y + 55, { steps: 5 }); await page.mouse.up();
  const after = await page.locator('#dc-card-activity-overview').boundingBox();
  assert.ok(after.width > before.width && after.height > before.height, 'new card did not resize');
  for (const title of ['Timeline', 'Services', 'Users', 'Categories', 'Countries']) await add('Activity ' + title);
  assert.equal(requests, 1, 'visible cards did not share their data request');
  await page.locator('#dashSaveBtn').click();
  await page.waitForFunction(() => document.querySelector('#dc-activity-users')?.textContent.includes('مستخدم تجريبي'));
  assert.equal(await page.locator('.dc-activity-card:visible').count(), 6);
  assert.equal(await page.locator('.dc-activity-card .activity-donut svg').count(), 2);
  assert.ok((await page.locator('#dc-card-activity-overview').textContent()).includes('sync disabled'));
  await page.waitForFunction(() => localStorage.getItem('mikrodash_dashboard_layout_v12')?.includes('dc-card-activity-overview'));
  const server = await context.request.get(base + '/api/dashboard-layout');
  const saved = await server.json(); assert.equal(saved.cards.filter(card => card.visible && card.id.includes('activity-')).length, 6);
  await page.reload(); await count(12); assert.equal(await page.locator('.dc-activity-card:visible').count(), 6);
  const third = await browser.newContext({ viewport: { width: 1280, height: 1000 } });
  await third.addCookies([{ name: 'mikrodash_sid', value: 'activity-test-token', url: base }]);
  const portable = await third.newPage(); await portable.goto(base + '/home'); await portable.waitForSelector('#dc-activity-overview strong');
  assert.equal(await portable.locator('.dc-activity-card:visible').count(), 6, 'server layout did not follow the user to another browser'); await third.close();
  await edit(); await page.locator('#dc-card-activity-services .dash-remove-btn').click();
  await page.locator('#dashDiscardBtn').click(); assert.ok(await page.locator('#dc-card-activity-services').isVisible(), 'Discard lost the old layout');
  await edit(); await page.locator('#dc-card-activity-services .dash-remove-btn').click(); await page.locator('#dashSaveBtn').click();
  await page.reload(); await count(12); assert.ok(await page.locator('#dc-card-activity-services').isHidden());
  await edit(); await add('Activity Services'); await page.locator('#dashSaveBtn').click(); await count(12);
  // Native drilldown navigation opens the real Activity page with the filter.
  await page.locator('#dc-activity-services [data-filter="service"]').first().click();
  await page.waitForURL('**/activity?**'); assert.ok(new URL(page.url()).searchParams.get('service'));
  await page.waitForSelector('#activityTableBody [data-filter="domain"]'); await page.goBack(); await count(12);
  const prior = requests; await context.request.post(base + '/fixture/append'); await socket('activity:changed', { routerId: 'r1', at: Date.now() }); await count(13);
  assert.equal(requests, prior + 1, 'invalidation duplicated data requests');
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('fixture-page', { detail: 'logs' })));
  const hidden = requests; await socket('activity:changed', { routerId: 'r1', at: Date.now() }); await page.waitForTimeout(650); assert.equal(requests, hidden, 'hidden dashboard fetched Activity');
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('fixture-page', { detail: 'dashboard' }))); await count(13);
  await socket('router:active', { activeId: 'r2' }); await count(1); assert.ok(!(await page.locator('#dc-activity-users').textContent()).includes('مستخدم تجريبي'));
  await socket('router:active', { activeId: 'r1' }); await count(13);
  await page.screenshot({ path: '/tmp/mikrodash-activity-cards-desktop.png', fullPage: true });
  const checkAxe = async label => {
    const axe = new AxeBuilder({ page }).include('.dc-activity-card').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']);
    const result = await axe.analyze(); assert.deepEqual(result.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), [], label);
  };
  await checkAxe('desktop accessibility');
  await page.locator('#dc-card-activity-overview .dc-activity-open').focus(); assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Open Activity Overview');
  await page.setViewportSize({ width: 375, height: 900 });
  await page.screenshot({ path: '/tmp/mikrodash-activity-cards-mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile horizontal overflow'); await checkAxe('mobile dark accessibility');
  await page.evaluate(() => document.documentElement.dataset.theme = 'light'); await checkAxe('mobile light accessibility');
  await page.screenshot({ path: '/tmp/mikrodash-activity-cards-light.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 1000 }); await page.evaluate(() => { delete document.documentElement.dataset.theme; });
  await context.request.post(base + '/fixture/revoke'); await socket('perms:changed');
  await page.waitForFunction(() => document.querySelector('#dc-activity-overview')?.textContent.includes('permissions'));
  assert.equal(await page.locator('#dc-activity-overview strong').count(), 0, 'permission revocation retained old data');
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('fixture-caps', { detail: false }))); await edit(); await page.locator('#dc-card-activity-services .dash-remove-btn').click(); await page.locator('#dashAddCardBtn').click();
  assert.equal(await page.locator('#dashAddPanel button').filter({ hasText: 'Activity ' }).count(), 0, 'denied source offered in the card picker');
  await page.locator('#dashDiscardBtn').click();
  assert.deepEqual(errors, []);
  console.log('dashboard journey: six optional cards, shared demand, resize, add/save/discard/remove, portable persistence, Arabic, drilldown, invalidation, hidden dashboard, router switch, revoked permissions, keyboard, 375/1280, dark/light and axe zero violations passed');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
